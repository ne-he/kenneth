/*
  Demo dataset for the prototype.

  Coordinates come from OpenStreetMap (Nominatim lookup, 18 and 19 Sep 2026).
  Gates of the venues added on 19 Sep sit where OSM has a parking entrance or
  a service road next to the building. Everything else here (capacity, gates,
  tariffs, charger counts, tenants, floors, valet fees) is demo data for a low
  fidelity prototype. None of it has been confirmed with the building
  managers, and the app says so in the UI.

  The places added on 5 Oct 2026 (more campuses, malls and office towers in
  the same blocks) take their coordinates from Nominatim that day, and each
  gate sits on a car park barrier (lift gate or toll booth) or parking
  entrance mapped in OSM within 280 m of the place, at least 50 m from its
  other gates and never one another place already uses. Walking links only
  join places of the same kind, so a full mall never points at an office or
  campus car park.

  Campuses are grouped with the malls around them on purpose. The team picked
  density over reach: a few blocks where every car park is covered beat a
  thin layer over the whole city.
*/

